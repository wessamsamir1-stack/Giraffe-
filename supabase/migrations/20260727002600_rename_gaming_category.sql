-- Giraffe — 26. إعادة تسمية قسم الألعاب
--
-- «ألعاب وأجهزة ألعاب» فيها كلمة «ألعاب» مرتين، وكانت بتتقسم على
-- سطرين في شريط الأقسام وتسيب كلمة وحيدة في سطر لوحدها.
--
-- بقت «ألعاب وأجهزتها» — نفس المعنى، وبتدخل سطر واحد.
--
-- -----------------------------------------------------------------------------
-- ليه ملف جديد ومش تعديل على ملف البذور
--
-- ملف البذور `20260727001500_seed_catalog.sql` **اتعدّل كمان** — لازم،
-- لأن الكتالوج في الدارت هو المصدر الوحيد للحقيقة والمولّد بيطلّعه منه.
--
-- بس التعديل ده لوحده مابيوصلش لأي قاعدة شغّالة: الترحيل مسجّل إنه
-- اتنفّذ خلاص، فـ `supabase db push` مابيعيدش تشغيله مهما اتغيّر
-- محتواه.
--
-- فالنتيجة لازم تيجي من الاتنين مع بعض:
--   - القواعد الجديدة بتاخد الاسم الصح من ملف البذور.
--   - القواعد الموجودة بتاخده من الملف ده.
--
-- والاتنين بينتهوا لنفس الحالة بالظبط — وده الشرط اللي أي تعديل على
-- بيانات مزروعة لازم يحققه.
-- =============================================================================

update public.categories
   set name_ar = 'ألعاب وأجهزتها'
 where id = 'gaming'
   and name_ar = 'ألعاب وأجهزة ألعاب';

-- `and name_ar = ...` مش زيادة: لو حد غيّر الاسم بإيده من اللوحة،
-- الترحيل ده مايدهسش تغييره.
